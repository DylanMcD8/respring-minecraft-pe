#!/usr/bin/env python3
"""Generate a guarded, straight-line native translation of the profiled gradient block.
Uses only the preserved local disassembly/binary, no runtime compilation or JIT.
"""
from pathlib import Path
import sys
import re
root=Path(__file__).resolve().parent.parent
start,end=0x4fb92,0x4fe0a
lines=[]
for line in (Path(sys.argv[1])/'disassembly-armv7.txt').read_text().splitlines():
 m=re.match(r'^([0-9a-f]{8})\s+[0-9a-f]+\s+(\S+)\s*(.*)',line)
 if m and start<=int(m[1],16)<end:lines.append((int(m[1],16),m[2],m[3]))
regs={f'r{i}':i for i in range(16)}|{'lr':14,'sp':13}
def r(s):return f'r[{regs[s.strip()]}]'
def val(s):return str(int(s.strip()[1:],0))+'u32' if s.strip().startswith('#') else r(s)
def cond(c):return {'lo':'flags&0x20000000==0','eq':'flags&0x40000000!=0','ne':'flags&0x40000000==0'}[c]
def translate(op,args):
 a=[x.strip() for x in args.split(',')]
 if op in ['add','add.w']:
  if len(a)==2:return f'{r(a[0])}={r(a[0])}.wrapping_add({val(a[1])});'
  rhs=val(a[2]);rhs=f'{rhs}.wrapping_shl({int(a[3].split("#")[1])})' if len(a)==4 else rhs
  return f'{r(a[0])}={r(a[1])}.wrapping_add({rhs});'
 if op in ['ldr','ldr.w']:
  dest,addr=args.split(',',1);parts=[x.strip()for x in addr.strip()[1:-1].split(',')]
  address=r(parts[0])
  if len(parts)>1:
   off=val(parts[1]);off=f'{off}.wrapping_shl({int(parts[2].split("#")[1])})' if len(parts)>2 else off
   address=f'{address}.wrapping_add({off})'
  return f'{r(dest)}=cpu.data_r_u32(mem,{address})?;'
 if op=='and':return f'{r(a[0])}={r(a[1])}&{val(a[2])};'
 if op=='cmp':return f'flags=cmp(flags,{r(a[0])},{val(a[1])});'
 if op=='tst.w':return f'flags=nz(flags,{r(a[0])}&{val(a[1])});'
 if op=='mov':return f'{r(a[0])}={r(a[1])};'
 if op.startswith('it'):return '// Conditional execution is expressed directly below.'
 if op.endswith('.f32'):
  name=op[:-4];condition=None
  for c in ['lo','eq','ne']:
   if name.endswith(c):condition=c;name=name[:-2];break
  idx=[int(x[1:])for x in a];d=idx[0]
  if name=='vmov':code=f'f[{d}]=f[{idx[1]}];'
  elif name=='vneg':code=f'f[{d}]=f[{idx[1]}]^0x80000000;'
  elif name in ['vadd','vsub','vmul']:
   oper={'vadd':'+','vsub':'-','vmul':'*'}[name];code=f'f[{d}]=(f32::from_bits(f[{idx[1]}]){oper}f32::from_bits(f[{idx[2]}])).to_bits();'
  elif name=='vmla':code=f'let product=f32::from_bits(f[{idx[1]}])*f32::from_bits(f[{idx[2]}]); f[{d}]=(f32::from_bits(f[{d}])+product).to_bits();'
  else:raise ValueError((op,args))
  return f'if {cond(condition)} {{{code}}}' if condition else code
 raise ValueError((op,args))
def emit(lo,hi,indent='    '):
 out=[];i=lo
 while i<hi:
  pc,op,args=lines[i];out.append(f'{indent}// {pc:08x}: {op} {args}\n{indent}used+=1;')
  if op=='blo':
   target=int(args,0);j=next(j for j in range(i+1,len(lines))if lines[j][0]==target)
   out.append(f'{indent}if !(flags&0x20000000==0) {{');out+=emit(i+1,j,indent+'    ');out.append(indent+'}');i=j
  else:out.append(indent+translate(op,args));i+=1
 return out
binary=(Path(sys.argv[1])/'minecraftpe').read_bytes()[start:end]
header='''/* This Source Code Form is subject to the Mozilla Public License, v. 2.0. */
//! Generated by Private/Tools/generate-noise-block.py from the preserved ARMv7
//! gradient calculation. Straight-line Rust, no runtime decoding or JIT.
//! VMLA retains separate single-precision multiply and add rounding.
use super::{InterpreterCpu, Mem, Ptr, PC};
pub(super) struct Prediction {pub regs:[u32;16],pub fp:[u32;64],pub cpsr:u32,pub used:u64}
fn nz(flags:u32,v:u32)->u32{(flags&0x3fffffff)|(v&0x80000000)|(u32::from(v==0)<<30)}
fn cmp(flags:u32,a:u32,b:u32)->u32{
    let(v,c,o)=InterpreterCpu::add_with_carry(a,!b,true);
    (flags&0x0fffffff)|(v&0x80000000)|(u32::from(v==0)<<30)|(u32::from(c)<<29)|(u32::from(o)<<28)
}
'''
header+=f'pub(super) const ENTRY:u32=0x{start:x};\npub(super) const MAX_INSTRUCTIONS:u64={len(lines)};\npub(super) const CODE:&[u8]=&['+','.join(f'0x{x:02x}'for x in binary)+'];\n'
header+='''pub(super) fn predict(cpu:&InterpreterCpu,mem:&Mem)->Option<Prediction>{
    if !cpu.is_thumb()||cpu.in_it_block()||cpu.excl_addr.is_some()
        ||mem.get_bytes_fallible(Ptr::from_bits(ENTRY),CODE.len() as u32)?!=CODE{return None;}
    let mut r=cpu.regs;let mut f=cpu.extregs;let mut flags=cpu.cpsr;let mut used=0;
'''
source=header+'\n'.join(emit(0,len(lines)))+f'\n    r[PC]=0x{end:x};\n    Some(Prediction{{regs:r,fp:f,cpsr:flags,used}})\n}}\n'
(root/'CompatibilityProbe/compatibility-core/src/cpu/interpreter/minecraft_noise.rs').write_text(source)
print('Generated',len(lines),'original instructions;',len(binary),'guard bytes')
